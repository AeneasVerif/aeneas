(** Given a translated LLBC crate, this module groups the declarations into
    source-file buckets, builds the dependency graph between the buckets, and
    computes its strongly-connected components. *)

open LlbcAst
open LlbcAstUtils
open Types
open Meta

(** Where a declaration/reference lands in the projected file graph.

    The external buckets are diagnostic buckets for non-local referenced
    declarations. They do not imply that the current extraction backend will
    emit a corresponding external template file. *)
type bucket =
  | BFile of string
      (** A local source file, keyed on its path below the crate's source root
          (e.g. ["foo.rs"], ["geometry/mod.rs"]) — see
          {!FileMapping.normalize_source_path}. The path charon actually
          reported is kept separately in {!t.bucket_source}, for diagnostics. *)
  | BExternalTypes  (** Referenced external type declarations. *)
  | BExternalFuns  (** Referenced external functions/globals/traits. *)
[@@deriving show, ord]

module BucketOrd : Collections.OrderedType with type t = bucket = struct
  type t = bucket

  let compare = compare_bucket
  let to_string = show_bucket
  let pp_t = pp_bucket
  let show_t = show_bucket
end

module BucketSet = Collections.MakeSet (BucketOrd)
module BucketMap = Collections.MakeMap (BucketOrd)

(** The source path a local item's Rust *module* path implies, under the usual
    [crate::a::b -> src/a/b.rs] convention. Used only as a fallback when the
    item's span is unusable (see [bucket_of_item]). *)
let source_path_of_name (name : Types.name) : string =
  (* A trailing [PeTarget] (multi-target mode) would otherwise end the run of
     identifiers early and make us mistake the item's own name for a module. *)
  let name =
    match strip_target_suffix name with
    | _crate :: rest -> rest
    | [] -> []
  in
  (* The leading run of plain identifiers. *)
  let rec idents (n : Types.path_elem list) : string list =
    match n with
    | PeIdent (s, _) :: rest -> s :: idents rest
    | _ -> []
  in
  let prefix = idents name in
  (* If no impl element cut the run short, the last identifier is the item's own
     name rather than a module. *)
  let modules =
    if List.length prefix = List.length name then
      match List.rev prefix with
      | _item :: rev_mods -> List.rev rev_mods
      | [] -> []
    else prefix
  in
  match modules with
  | [] -> "src/lib.rs"
  | _ -> "src/" ^ String.concat "/" modules ^ ".rs"

(** The bucket an item belongs to, or [None] if we can't find its metadata.

    Bucketing is gated on [is_local]: a local item goes to a [BFile] keyed on
    its source path, a non-local item to an external bucket by kind.

    [on_foreign_span] is called for a local item whose span points into another
    crate. *)
let bucket_of_item (crate : crate) ~(on_foreign_span : string -> unit)
    ~(on_source : bucket -> string -> unit) (id : item_id) : bucket option =
  match crate_get_item_meta crate id with
  | None -> None
  | Some meta ->
      if not meta.is_local then
        Some
          (match id with
          | IdType _ -> BExternalTypes
          | _ -> BExternalFuns)
      else
        let file = meta.span.data.file in
        let path = Meta.path_of_file_name file.name in
        (* Canonicalize: charon's paths are relative to the cargo invocation
           directory (the workspace root for a workspace member), and the
           fallback below reconstructs a path of its own. Both must reduce to
           the same key for items of the same file to share a bucket. *)
        if file.crate_name = crate.name then (
          let b = BFile (FileMapping.normalize_source_path path) in
          on_source b path;
          Some b)
        else (
          (* Workaround for a charon bug: an item generated by a `macro_rules!`
             macro from another crate is local, but its span points at the macro
             definition, which may not even appear in this crate's file table.
             Charon documents [span.data] as already being the macro call site
             (and [generated_from_span] as the definition), but that only holds
             inside bodies, not for [item_meta]. Taking the span at face value
             here files the item under a foreign path and emits a module
             mirroring the other crate's tree.

             Until charon reports the call site, fall back to the Rust module
             path, which is always local and names the file the macro was
             invoked from. That convention is not universal ([#[path]], inline
             [mod] blocks, and [mod.rs] all break it), so the item may land in
             a module of its own rather than merging with its file-mates — still
             a local, sensible tree, unlike the alternative. *)
          on_foreign_span path;
          let reconstructed = source_path_of_name meta.name in
          let b = BFile (FileMapping.normalize_source_path reconstructed) in
          on_source b reconstructed;
          Some b)

type t = {
  crate_name : string;
  item_bucket : bucket AnyDeclIdMap.t;
      (** Every declaration's bucket, computed once. Items whose metadata can't
          be found (e.g. ids a prepass removed from the maps but not from
          [crate.declarations]) are absent. *)
  bucket_source : string BucketMap.t;
      (** For each file bucket, the path as charon reported it — which the
          canonical bucket key has stripped to the crate's source root. Only for
          diagnostics: it is what the user can actually find on disk. *)
  members : item_id list BucketMap.t;
  edges : BucketSet.t BucketMap.t;
      (** [edges] maps a bucket to the buckets it uses. Self-edges are omitted.
      *)
  sccs : bucket SCC.sccs;
}

let compute (crate : crate) : t =
  (* Enumerate the declarations through [crate.declarations] — the same source
     of truth the emitter partitions — and map each item to its bucket once. *)
  (* [declaration_group_to_list] comes from charon's [GAstUtils] via
     [LlbcAstUtils]. *)
  let items = List.concat_map declaration_group_to_list crate.declarations in
  (* Local items whose span pointed into another crate, counted per offending
     file so the workaround in [bucket_of_item] reports once per file instead of
     once per item. *)
  let foreign_spans : (string, int) Hashtbl.t = Hashtbl.create 4 in
  let on_foreign_span (path : string) : unit =
    Hashtbl.replace foreign_spans path
      (1 + Option.value (Hashtbl.find_opt foreign_spans path) ~default:0)
  in
  (* The path charon reported for each file bucket, kept for diagnostics. All
     items of a bucket agree on it, bar the [mod.rs]-style imprecision of the
     macro fallback, where first-seen is as good as any. *)
  let bucket_source : string BucketMap.t ref = ref BucketMap.empty in
  let on_source (b : bucket) (path : string) : unit =
    if not (BucketMap.mem b !bucket_source) then
      bucket_source := BucketMap.add b path !bucket_source
  in
  let item_bucket : bucket AnyDeclIdMap.t =
    List.fold_left
      (fun acc id ->
        match bucket_of_item crate ~on_foreign_span ~on_source id with
        | None ->
            (* No metadata: a prepass removed the id from the decl maps but not
               from [crate.declarations]. The item can't be bucketed, so it is
               dropped from the split output ([FilePlan.place_by_file] also
               warns when this drops a whole declaration group). *)
            [%warn_opt_span] None
              ("Multi-file extraction: no metadata found for " ^ show_item_id id
             ^ "; it will not appear in the output");
            acc
        | Some b -> AnyDeclIdMap.add id b acc)
      AnyDeclIdMap.empty items
  in
  Hashtbl.iter
    (fun path n ->
      [%warn_opt_span] None
        (Printf.sprintf
           "Multi-file extraction: %d local declaration(s) have a span \
            pointing into %s, which is not a file of this crate. Most likely \
            they come from a macro defined in another crate. Placing them by \
            their Rust module path instead of by that file; the resulting \
            module may not merge with the rest of the file the macro was \
            invoked from."
           n path))
    foreign_spans;
  let bucket_of (id : item_id) : bucket option =
    AnyDeclIdMap.find_opt id item_bucket
  in

  (* Map each bucket to the items it contains. *)
  let members : item_id list BucketMap.t ref = ref BucketMap.empty in
  List.iter
    (fun id ->
      match bucket_of id with
      | None -> ()
      | Some b ->
          members :=
            BucketMap.update b
              (function
                | None -> Some [ id ]
                | Some l -> Some (id :: l))
              !members)
    items;

  (* Build the bucket dependency graph from the item-level use graph.
     [graph_of_uses] maps each *used* item to the set of items that use it, so
     for every (used, user) pair we add an edge user_bucket -> used_bucket. *)
  let uses = Deps.compute_graph_of_uses crate in
  let edges : BucketSet.t BucketMap.t ref = ref BucketMap.empty in
  let add_edge (src : bucket) (dst : bucket) : unit =
    if BucketOrd.compare src dst <> 0 then
      edges :=
        BucketMap.update src
          (fun s ->
            Some (BucketSet.add dst (Option.value s ~default:BucketSet.empty)))
          !edges
  in
  AnyDeclIdMap.iter
    (fun used users ->
      match bucket_of used with
      | None -> ()
      | Some ub ->
          Deps.ItemInfoSet.iter
            (fun (user : Deps.item_info) ->
              match bucket_of user.id with
              | None -> ()
              | Some usb -> add_edge usb ub)
            users)
    uses.graph;

  (* Compute the SCCs of the bucket graph: every node is a bucket, and the
     reordering keeps the topological (dependency-first) order. *)
  let module Scc = SCC.Make (BucketOrd) in
  let graph_list : (bucket * BucketSet.t) list =
    List.map
      (fun (b, _) ->
        (b, Option.value (BucketMap.find_opt b !edges) ~default:BucketSet.empty))
      (BucketMap.bindings !members)
  in
  let sccs = Scc.compute graph_list in

  {
    crate_name = crate.name;
    item_bucket;
    bucket_source = !bucket_source;
    members = !members;
    edges = !edges;
    sccs;
  }

(** How to name a bucket to the user: for a file, the path charon reported,
    which is what they can find on disk. Falls back to the canonical key for a
    bucket the graph doesn't know (it always does, in practice). *)
let display_bucket (g : t) (b : bucket) : string =
  match b with
  | BFile p -> Option.value (BucketMap.find_opt b g.bucket_source) ~default:p
  | BExternalTypes -> "<external types>"
  | BExternalFuns -> "<external funs>"

(** Render the report.

    [get_name] turns an item id into a human-readable Rust name. *)
let render (graph : t) ~(get_name : item_id -> string) : string =
  (* Render the report. *)
  let buf = Buffer.create 1024 in
  let line fmt =
    Printf.ksprintf (fun s -> Buffer.add_string buf (s ^ "\n")) fmt
  in

  let bucket_list = List.map fst (BucketMap.bindings graph.members) in
  let merges =
    List.filter
      (fun (_, bs) -> List.length bs > 1)
      (SCC.SccId.Map.bindings graph.sccs.sccs)
  in

  line "================ FILE GRAPH ================";
  line "Crate: %s" graph.crate_name;
  line "Buckets: %d   Forced merges (cyclic SCCs): %d" (List.length bucket_list)
    (List.length merges);
  line "";

  line "---- Buckets and their declarations ----";
  List.iter
    (fun b ->
      let ids = Option.value (BucketMap.find_opt b graph.members) ~default:[] in
      line "%s  (%d declarations)" (display_bucket graph b) (List.length ids);
      List.iter
        (fun id ->
          line "    [%-11s] %s" (item_id_to_kind_name id) (get_name id))
        (List.rev ids))
    bucket_list;
  line "";

  line "---- Bucket dependency edges (importer -> imported) ----";
  List.iter
    (fun b ->
      let deps =
        Option.value (BucketMap.find_opt b graph.edges) ~default:BucketSet.empty
      in
      if not (BucketSet.is_empty deps) then
        line "    %s  ->  %s" (display_bucket graph b)
          (String.concat ", "
             (List.map (display_bucket graph) (BucketSet.elements deps))))
    bucket_list;
  line "";

  line "---- Strongly-connected components ----";
  line "Each SCC becomes exactly one Lean file; an SCC with >1 bucket is a";
  line "forced merge (those source files must share a single Lean module).";
  List.iter
    (fun (scc_id, bs) ->
      let dep_ids =
        Option.value
          (SCC.SccId.Map.find_opt scc_id graph.sccs.scc_deps)
          ~default:SCC.SccId.Set.empty
      in
      let deps_str =
        if SCC.SccId.Set.is_empty dep_ids then ""
        else
          "   (depends on SCC "
          ^ String.concat ", "
              (List.map SCC.SccId.to_string (SCC.SccId.Set.elements dep_ids))
          ^ ")"
      in
      let tag = if List.length bs > 1 then "  <== MERGED (cyclic)" else "" in
      line "  SCC %s: %s%s%s"
        (SCC.SccId.to_string scc_id)
        (String.concat " + " (List.map (display_bucket graph) bs))
        deps_str tag)
    (SCC.SccId.Map.bindings graph.sccs.sccs);
  line "=======================================================================";

  Buffer.contents buf
